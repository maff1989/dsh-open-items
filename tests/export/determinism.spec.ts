/**
 * The determinism proof (DESIGN §7.4.7 rule 7).
 *
 * Same records + same options ⇒ byte-identical output, proven rather than
 * asserted: two runs over differently-ordered fresh copies, a SHA-256 of each
 * result, and the committed golden files. A third property is checked
 * separately: `generatedAt` is the *only* value that may change the bytes of an
 * otherwise identical export, and no timezone or locale may influence them.
 */
import { describe, expect, it } from 'vitest'

import {
  CSV_COLUMNS,
  EXPORT_SCHEMA_VERSION,
  JSONL_HEADER_KEYS,
  JSONL_RECORD_KEYS,
  exportChunks,
  exportFileName,
  generateExport,
  selectExportRecords,
  sortForExport,
  toCsv,
  toHtml,
  toJsonl,
  utf8ByteLength,
  type ExportFormat,
  type ExportOptions,
} from '../../src/shared/export'
import type { OpenItemRecord } from '../../src/shared/schema'
import { fixtureRecords, fixedOptions, FIXED_GENERATED_AT, shuffleWithSeed } from './fixtures'
import { matchGolden, parseCsv, readGolden, sha256 } from './helpers'

const FORMATS: readonly ExportFormat[] = ['csv', 'jsonl', 'html']

/** One deterministic export of a fixed record set. */
function build(format: ExportFormat, seed = 1): string {
  const options: ExportOptions = fixedOptions({ format })
  const records = shuffleWithSeed(fixtureRecords(), seed)
  return generateExport(records, options).content
}

describe('determinism', () => {
  for (const format of FORMATS) {
    it(`two runs of the same ${format} fixture are byte-identical`, () => {
      const first = build(format, 7)
      const second = build(format, 999)
      expect(second).toBe(first)
      // The hash is the proof, and it is also what the golden file commits to.
      expect(sha256(second)).toBe(sha256(first))
      expect(sha256(first)).toBe(sha256(readGolden(`register.${format}`)))
    })
  }

  it('input order never changes the bytes', () => {
    for (const format of FORMATS) {
      const orders = [1, 2, 3, 42, 12345, 0xffffffff].map(seed => build(format, seed))
      expect(new Set(orders).size).toBe(1)
    }
  })

  it('fresh, structurally-equal record objects produce identical bytes', () => {
    for (const format of FORMATS) {
      const options = fixedOptions({ format })
      const first = generateExport(fixtureRecords(), options).content
      // `fixtureRecords()` builds new objects every call; JSON-equal, not identical.
      const second = generateExport(fixtureRecords(), options).content
      expect(second).toBe(first)
    }
  })

  it('the streaming chunks join to exactly the generated bytes', () => {
    for (const format of FORMATS) {
      const options = fixedOptions({ format })
      const file = generateExport(fixtureRecords(), options)
      const chunkSet = exportChunks(fixtureRecords(), options)
      expect(chunkSet.chunks.join('')).toBe(file.content)
      expect(chunkSet.byteLength).toBe(Buffer.byteLength(file.content, 'utf8'))
      expect(file.byteLength).toBe(chunkSet.byteLength)
      expect(chunkSet.filename).toBe(file.filename)
    }
  })

  it('generatedAt is the only value that may change the bytes', () => {
    const later = FIXED_GENERATED_AT + 3_600_000
    const a = fixedOptions({ format: 'html' })
    const b = fixedOptions({ format: 'html', generatedAt: later })
    const first = toHtml(fixtureRecords(), a)
    const second = toHtml(fixtureRecords(), b)
    // +1 h: 2026-11-14T00:45:00.000Z, rendered as `2026-11-14 00:45 UTC`.
    const normalized = first
      .replaceAll('2026-11-13T23:45:00.000Z', '2026-11-14T00:45:00.000Z')
      .replaceAll('2026-11-13 23:45 UTC', '2026-11-14 00:45 UTC')
    // The generator's only clock read is `options.generatedAt`; normalizing both
    // of its rendered forms must reproduce the other export exactly.
    expect(normalized).toBe(second)
  })

  it('does not read the timezone', () => {
    const original = process.env['TZ']
    const results: string[] = []
    try {
      for (const zone of ['UTC', 'Pacific/Kiritimati', 'America/Adak', 'Asia/Kolkata']) {
        process.env['TZ'] = zone
        results.push(FORMATS.map(format => build(format, 3)).join('\u0000'))
      }
    } finally {
      if (original === undefined) delete process.env['TZ']
      else process.env['TZ'] = original
    }
    expect(new Set(results).size).toBe(1)
    // Every formatted instant is UTC and carries its `Z`.
    expect(build('csv')).toContain('2026-11-13T22:41:00.000Z')
  })

  it('pins the contract constants: export schema, columns, key orders', () => {
    expect(EXPORT_SCHEMA_VERSION).toBe(1)
    expect(CSV_COLUMNS).toEqual([
      'resolvedAt', 'sessionTitle', 'sessionId', 'itemId', 'title', 'kind', 'severity', 'outcome',
      'decision', 'source', 'acknowledged', 'archived', 'excerpt', 'quote',
    ])
    expect(JSONL_RECORD_KEYS).toEqual([
      'type', 'exportSchemaVersion', 'schemaVersion', 'id', 'origin', 'kind', 'state', 'tier',
      'severity', 'title', 'body', 'quote', 'options', 'source', 'blocking', 'reply', 'deliveries',
      'occurrences', 'dedupeKey', 'detectedBy', 'firstSeenAt', 'lastSeenAt', 'updatedAt', 'version',
      'snoozedUntil', 'resolution', 'resolutionLog', 'acknowledgement', 'resolvedAt', 'reopenCount',
      'retention', 'history', 'deletedAt',
    ])
    expect(JSONL_HEADER_KEYS).toEqual([
      'type', 'exportSchemaVersion', 'schemaVersion', 'pluginVersion', 'generatedAt', 'filterLabel',
      'recordCount', 'earlierRecordsPruned', 'includeArchive', 'includeExcerpts',
      'archivedIncluded', 'archivedExcluded',
    ])
  })

  it('sorts by resolvedAt descending with an id tie-break, independent of input order', () => {
    const [first] = fixtureRecords()
    if (first === undefined) throw new Error('fixture missing')
    const at = Date.UTC(2026, 10, 1, 12, 0, 0)
    const tie: OpenItemRecord[] = ['c', 'a', 'b'].map((suffix, index) => ({
      ...first,
      id: `item-tie-${suffix}`,
      resolvedAt: at,
      resolution: { kind: 'answered', at, actor: 'user', payload: { type: 'text', text: `choice ${String(index)}` } },
    }))
    expect(sortForExport(tie).map(record => record.id)).toEqual(['item-tie-a', 'item-tie-b', 'item-tie-c'])
    expect(sortForExport([...tie].reverse()).map(record => record.id)).toEqual(['item-tie-a', 'item-tie-b', 'item-tie-c'])
  })

  it('keeps file names deterministic, including the empty and non-ASCII cases', () => {
    const html = fixedOptions({ format: 'html' })
    const csv = fixedOptions({ format: 'csv' })
    expect(exportFileName(selectExportRecords(fixtureRecords(), html), html))
      .toBe('open-items-20261113T224100Z-6-30-days-all-sources.html')
    expect(exportFileName(selectExportRecords(fixtureRecords(), csv), csv))
      .toBe('open-items-20261113T224100Z-6-30-days-all-sources.csv')
    expect(exportFileName(selectExportRecords([], html), html)).toBe('open-items-empty-0-30-days-all-sources.html')
    const chinese = fixedOptions({ format: 'csv', filterLabel: '30 天 · 全部来源' })
    const slugName = exportFileName(selectExportRecords(fixtureRecords(), chinese), chinese)
    expect(slugName).toMatch(/^open-items-20261113T224100Z-6-filter-[0-9a-f]{8}\.csv$/u)
    // Same label twice ⇒ same name (a re-export overwrites, never duplicates).
    expect(exportFileName(selectExportRecords(fixtureRecords(), chinese), chinese)).toBe(slugName)
    // A different non-ASCII label is a different name.
    const other = fixedOptions({ format: 'csv', filterLabel: '7 天' })
    expect(exportFileName(selectExportRecords(fixtureRecords(), other), other)).not.toBe(slugName)
  })

  it('reorders nothing it should keep: every format has the same row count', () => {
    const options = fixedOptions({})
    const selection = selectExportRecords(fixtureRecords(), options)
    // Parse rather than count physical lines: embedded newlines live inside cells.
    const csvRows = parseCsv(toCsv(fixtureRecords(), options)).length - 2
    const jsonlRows = toJsonl(fixtureRecords(), { ...options, format: 'jsonl' }).trimEnd().split('\n').length - 1
    const htmlRows = toHtml(fixtureRecords(), { ...options, format: 'html' }).match(/<article\b/gu)?.length ?? 0
    expect(csvRows).toBe(selection.records.length)
    expect(jsonlRows).toBe(selection.records.length)
    expect(htmlRows).toBe(selection.records.length)
  })

  it('computes UTF-8 byte lengths identically to the platform encoder', () => {
    const samples = ['', 'ascii', '—', '日本語', '🦔', 'a🦔b', 'e\u0301', '\u0000control', 'mixed 日本 🦔 ✓']
    for (const sample of samples) {
      expect(utf8ByteLength(sample), `byte length for ${JSON.stringify(sample)}`).toBe(Buffer.byteLength(sample, 'utf8'))
    }
    // A lone surrogate encodes as three bytes (replacement character).
    expect(utf8ByteLength('\ud800')).toBe(3)
  })

  it('keeps the golden files themselves byte-stable', () => {
    // Reading twice must return the same bytes: the committed contract.
    expect(readGolden('register.csv')).toBe(readGolden('register.csv'))
    expect(matchGolden('register.csv', toCsv(fixtureRecords(), fixedOptions({ format: 'csv' }))))
      .toBe(readGolden('register.csv'))
  })
})
